// Carga SiCrecer en Supabase vía pooler (sin pasar por el MCP):
//  1) aplica las migraciones pendientes de supabase/migrations y las registra en supabase_migrations.schema_migrations
//  2) crea qa_resultados (tabla fuera de las migraciones)
//  3) trunca public, carga el export de Neon (JSONL), reinicia secuencias
//  4) verifica conteos
// Uso: node cargar_supabase.cjs <dirProyecto> <dirExport> [--solo-migraciones|--solo-datos]
const fs = require('fs'), path = require('path');
const proyecto = process.argv[2], exportDir = process.argv[3];
const modo = process.argv[4] || '';
const S = require('./_secretos.cjs')(proyecto);
const { Client } = S;
const conn = S.supabase();
const log = (...a) => console.log(new Date().toISOString().slice(11, 19), ...a);

async function migraciones(c) {
  const { rows: hechas } = await c.query(`select name from supabase_migrations.schema_migrations`);
  const set = new Set(hechas.map(r => r.name));
  const dir = path.join(proyecto, 'supabase', 'migrations');
  for (const f of fs.readdirSync(dir).sort()) {
    const m = /^(\d{14})_(.+)\.sql$/.exec(f); if (!m) continue;
    const [, version, name] = m;
    if (set.has(name)) { log('ya aplicada', name); continue; }
    const sql = fs.readFileSync(path.join(dir, f), 'utf8');
    await c.query('begin');
    try {
      await c.query(sql);
      await c.query(`insert into supabase_migrations.schema_migrations (version, name, statements) values ($1, $2, $3)`, [version, name, [sql]]);
      await c.query('commit');
      log('aplicada', name);
    } catch (e) { await c.query('rollback'); throw new Error(`migración ${name}: ${e.message}`); }
  }
  // Tabla creada a mano en Neon, fuera de las migraciones
  await c.query(`create table if not exists public.qa_resultados (
    id integer generated by default as identity primary key, caso text not null, resultado text not null,
    detalle text, creado timestamptz default now())`);
  await c.query(`alter table public.qa_resultados enable row level security`);
  const esquema = JSON.parse(fs.readFileSync(path.join(exportDir, '_esquema.json'), 'utf8'));
  for (const p of esquema.politicas.filter(p => p.tablename === 'qa_resultados')) {
    await c.query(`drop policy if exists ${p.policyname} on public.qa_resultados`);
    const roles = p.roles.replace(/[{}]/g, '');
    await c.query(`create policy ${p.policyname} on public.qa_resultados for ${p.cmd} to ${roles}` +
      (p.qual ? ` using (${p.qual})` : '') + (p.with_check ? ` with check (${p.with_check})` : ''));
  }
  log('qa_resultados lista');
}

async function datos(c) {
  const resumen = JSON.parse(fs.readFileSync(path.join(exportDir, '_resumen.json'), 'utf8'));
  const tablas = Object.keys(resumen.tablas);
  // Orden topológico por FKs del destino
  const { rows: fks } = await c.query(`select conrelid::regclass::text as hija, confrelid::regclass::text as padre
    from pg_constraint where contype='f' and connamespace='public'::regnamespace and conrelid <> confrelid`);
  const deps = {}; for (const t of tablas) deps[t] = new Set();
  for (const { hija, padre } of fks) { const h = hija.replace(/^public\./, ''), p = padre.replace(/^public\./, ''); if (deps[h] && deps[p]) deps[h].add(p); }
  const orden = []; const visto = new Set();
  const visitar = (t, pila = []) => { if (visto.has(t)) return; if (pila.includes(t)) throw new Error('ciclo FK: ' + [...pila, t].join('>')); for (const d of deps[t]) visitar(d, [...pila, t]); visto.add(t); orden.push(t); };
  tablas.forEach(t => visitar(t));
  log('orden de carga:', orden.join(' '));

  await c.query('begin');
  try {
    await c.query(`truncate table ${tablas.map(t => 'public."' + t + '"').join(', ')} restart identity cascade`);
    for (const t of orden) await c.query(`alter table public."${t}" disable trigger user`);
    let total = 0;
    for (const t of orden) {
      const archivo = path.join(exportDir, t + '.jsonl');
      const lineas = fs.readFileSync(archivo, 'utf8').split('\n').filter(Boolean);
      if (!lineas.length) { log(t, 0); continue; }
      const { rows: cols } = await c.query(`select column_name, data_type, udt_name from information_schema.columns where table_schema='public' and table_name=$1 order by ordinal_position`, [t]);
      const nombres = cols.map(x => x.column_name);
      const filas = lineas.map(l => JSON.parse(l));
      const faltan = Object.keys(filas[0]).filter(k => !nombres.includes(k));
      if (faltan.length) throw new Error(`${t}: columnas del export que no existen en destino: ${faltan.join(',')}`);
      const LOTE = 200;
      for (let i = 0; i < filas.length; i += LOTE) {
        const trozo = filas.slice(i, i + LOTE);
        const params = []; const tuplas = [];
        for (const f of trozo) {
          const vals = cols.map(col => {
            let v = f[col.column_name]; if (v === undefined) v = null;
            if (v !== null && (col.data_type === 'jsonb' || col.data_type === 'json')) v = JSON.stringify(v);
            if (v !== null && col.data_type === 'ARRAY' && Array.isArray(v)) v = v; // pg serializa arrays JS
            params.push(v); return `$${params.length}::${col.data_type === 'ARRAY' ? col.udt_name.replace(/^_/, '') + '[]' : col.data_type === 'USER-DEFINED' ? col.udt_name : col.data_type === 'character varying' ? 'text' : col.data_type === 'timestamp with time zone' ? 'timestamptz' : col.data_type === 'timestamp without time zone' ? 'timestamp' : col.data_type}`;
          });
          tuplas.push('(' + vals.join(',') + ')');
        }
        await c.query(`insert into public."${t}" (${nombres.map(n => '"' + n + '"').join(',')}) overriding system value values ${tuplas.join(',')}`, params);
      }
      total += filas.length; log(t, filas.length);
    }
    for (const t of orden) await c.query(`alter table public."${t}" enable trigger user`);
    // Secuencias: max(id)+1
    const { rows: seqs } = await c.query(`select s.sequencename, c.table_name, c.column_name from pg_sequences s
      join information_schema.columns c on c.column_default like '%'||s.sequencename||'%' or (c.table_schema='public' and pg_get_serial_sequence('public.'||c.table_name, c.column_name) = 'public.'||s.sequencename)
      where s.schemaname='public' and c.table_schema='public'`);
    for (const s of seqs) {
      const { rows: [{ m }] } = await c.query(`select coalesce(max("${s.column_name}"),0)::bigint as m from public."${s.table_name}"`);
      await c.query(`select setval('public.${s.sequencename}', greatest($1::bigint, 1), $1::bigint > 0)`, [m]);
      log('secuencia', s.sequencename, '→', m);
    }
    await c.query('commit');
    log('filas cargadas:', total);
  } catch (e) { await c.query('rollback'); throw e; }
}

async function verificar(c) {
  const resumen = JSON.parse(fs.readFileSync(path.join(exportDir, '_resumen.json'), 'utf8'));
  let ok = true;
  for (const [t, r] of Object.entries(resumen.tablas)) {
    const { rows: [{ n }] } = await c.query(`select count(*)::int as n from public."${t}"`);
    if (n !== r.filas) { ok = false; log('DIFERENCIA', t, 'neon', r.filas, 'supabase', n); }
  }
  const { rows: [o] } = await c.query(`select (select count(*) from pg_tables where schemaname='public') tablas,
    (select count(*) from pg_proc where pronamespace='public'::regnamespace) funciones,
    (select count(*) from pg_policies where schemaname='public') politicas,
    (select count(*) from pg_views where schemaname='public') vistas,
    (select count(*) from pg_trigger t join pg_class c on c.oid=t.tgrelid join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and not t.tgisinternal) triggers,
    (select count(*) from pg_tables where schemaname='public' and not rowsecurity) sin_rls`);
  log('objetos destino:', JSON.stringify(o), ok ? 'CONTEOS OK' : 'CONTEOS CON DIFERENCIAS');
}

(async () => {
  const c = new Client(conn); await c.connect();
  try {
    if (modo !== '--solo-datos') await migraciones(c);
    if (modo !== '--solo-migraciones') { await datos(c); await verificar(c); }
  } finally { await c.end(); }
})().catch(e => { console.error('ERROR', e.message); process.exit(1); });
